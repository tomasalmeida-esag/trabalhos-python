def Media(a, b, c):
    return (a + b + c) / 3


# Programa principal
num1 = float(input("Introduza o primeiro número: "))
num2 = float(input("Introduza o segundo número: "))
num3 = float(input("Introduza o terceiro número: "))

resultado = Media(num1, num2, num3)

print("Média =", resultado)